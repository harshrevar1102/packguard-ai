import urllib.parse
from app.models import Analysis, FindingStatus


class EmailReportBuilder:
    @staticmethod
    def build_report(analysis: Analysis, recipient: str = "") -> dict:
        subject = f"PackGuard AI Review: {analysis.product_name} Packaging Artwork Discrepancies"
        
        lines = [
            "Dear Review Team,",
            "",
            f"Please review the following packaging verification findings identified by PackGuard AI for {analysis.product_name} (Analysis ID: {analysis.id}).",
            "",
            "=== SUMMARY OF FINDINGS ===",
            f"• Mismatches: {analysis.summary.total_mismatches}",
            f"• Items Needing Review: {analysis.summary.total_needs_review}",
            f"• Verified Matches: {analysis.summary.total_matches}",
            "",
        ]

        mismatches = [f for f in analysis.findings if f.status == FindingStatus.MISMATCH]
        if mismatches:
            lines.append("=== CRITICAL MISMATCHES ===")
            for idx, f in enumerate(mismatches, 1):
                spec_ref = f"{f.spec_source.filename} ({f.spec_source.sheet}!{f.spec_source.cell})" if f.spec_source else "None"
                art_ref = f"{f.artwork_source.filename} (Page {f.artwork_source.page})" if f.artwork_source else "Not found on artwork"
                
                lines.append(f"{idx}. {f.field_name}")
                lines.append(f"   • Specification Value: {f.spec_value}")
                lines.append(f"   • Artwork Declared:    {f.artwork_value}")
                if f.expected_value:
                    lines.append(f"   • Expected Value:      {f.expected_value}")
                lines.append(f"   • Spec Reference:      {spec_ref}")
                lines.append(f"   • Artwork Location:    {art_ref}")
                lines.append(f"   • Issue Description:   {f.explanation}")
                if f.safe_fix_available:
                    lines.append(f"   • Fix Status:          Safe text correction candidate available")
                lines.append("")

        needs_review = [f for f in analysis.findings if f.status == FindingStatus.NEEDS_REVIEW]
        if needs_review:
            lines.append("=== ITEMS NEEDING REVIEW ===")
            for idx, f in enumerate(needs_review, 1):
                cur_len = sum(len(x) for x in lines)
                if cur_len > 4200 and idx < len(needs_review):
                    remaining = len(needs_review) - idx + 1
                    lines.append(f"... and {remaining} additional items flagged for visual review.")
                    break
                lines.append(f"{idx}. {f.field_name}")
                if f.spec_value:
                    lines.append(f"   • Spec Value:    {f.spec_value[:100]}")
                if f.artwork_value and f.artwork_value != "None":
                    lines.append(f"   • Artwork Text:  {f.artwork_value[:100]}")
                lines.append(f"   • Review Reason: {f.explanation[:140]}")
                lines.append("")

        if not mismatches and not needs_review:
            lines.append("All checked specification items match the artwork text layers cleanly.")
            lines.append("")

        lines.extend([
            "=== ACTION REQUIRED ===",
            "Please review the discrepancy details above and confirm required packaging revisions.",
            "",
            "Note on Attachments: All verification details and text comparisons are included directly in this email body. No file attachments required.",
            "",
            "— Generated by PackGuard AI Verification Engine"
        ])

        body = "\n".join(lines)
        
        # Build Gmail compose URL (omitting /u/0/ so it automatically uses whichever account the user is logged into)
        gmail_params = {
            "view": "cm",
            "fs": "1",
            "su": subject,
            "body": body,
        }
        if recipient:
            gmail_params["to"] = recipient
        gmail_url = "https://mail.google.com/mail/?" + urllib.parse.urlencode(gmail_params, quote_via=urllib.parse.quote)

        # Build standard mailto URL
        mailto_params = {
            "subject": subject,
            "body": body
        }
        encoded_mailto = urllib.parse.urlencode(mailto_params, quote_via=urllib.parse.quote)
        mailto_url = f"mailto:{recipient}?{encoded_mailto}"

        return {
            "recipient": recipient,
            "subject": subject,
            "body": body,
            "gmail_url": gmail_url,
            "mailto_url": mailto_url,
            "instruction": "All data is included in the email body. Add your recipient and send."
        }
